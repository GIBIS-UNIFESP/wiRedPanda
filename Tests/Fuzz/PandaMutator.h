// Appearances list entry: quint32(count=1) + QMap<"skinName": "test"> in Qt_5_12 wire format.
//
// Wire layout (45 bytes):
//   [0..3]   quint32(1)      — appearances count = 1
//   [4..7]   quint32(1)      — QMap size = 1 entry
//   [8..11]  quint32(16)     — "skinName" UTF-16 byte-length
//   [12..27] UTF-16-BE       — "skinName"
//   [28..31] quint32(10)     — QVariant typeId = QString
//   [32]     0x00            — isNull = false
//   [33..36] quint32(8)      — "test" UTF-16 byte-length
//   [37..44] UTF-16-BE       — "test"
//
// Splicing this sequence at the right position (after the output port list) exercises
// the skinName reading path in GraphicElement::loadNewFormat.
inline constexpr uint8_t kAppearanceEntry[] = {
    0,0,0,1,                                          // appearances count = 1
    0,0,0,1,                                          // QMap size = 1 entry
    0,0,0,16,                                         // "skinName" UTF-16 byte-length
    0,'s',0,'k',0,'i',0,'n',0,'N',0,'a',0,'m',0,'e', // "skinName" as UTF-16-BE
    0,0,0,10,                                         // QVariant typeId = QString (10)
    0,                                                // isNull = false
    0,0,0,8,                                          // "test" UTF-16 byte-length
    0,'t',0,'e',0,'s',0,'t',                          // "test" as UTF-16-BE
};

// Element type patches as quint64 big-endian (8 bytes each), and element sequence patches: 4-byte
// GraphicElement::Type + 8-byte ElementType. Splicing a 12-byte sequence at once creates a valid element header that
// guides the fuzzer to the element-loading code path in one mutation step. Built on first use.
struct ElementPatches {
    std::vector<std::vector<uint8_t>> types;
    std::vector<std::vector<uint8_t>> sequences;
};

inline const ElementPatches &elementPatches()
{
    static const ElementPatches patches = [] {
        ElementPatches built;
        // All valid ElementType enum values: InputButton (1) to Display16 (33)
        for (quint64 v = 1; v <= 33; ++v) {
            // 8-byte quint64 element-type patch
            std::vector<uint8_t> patch(8);
            patch[0] = uint8_t(v >> 56); patch[1] = uint8_t(v >> 48);
            patch[2] = uint8_t(v >> 40); patch[3] = uint8_t(v >> 32);
            patch[4] = uint8_t(v >> 24); patch[5] = uint8_t(v >> 16);
            patch[6] = uint8_t(v >>  8); patch[7] = uint8_t(v);

            // 12-byte sequence: GraphicElement::Type (0x00010003) + ElementType quint64
            std::vector<uint8_t> seq = {0, 1, 0, 3};
            seq.insert(seq.end(), patch.begin(), patch.end());

            built.types.push_back(std::move(patch));
            built.sequences.push_back(std::move(seq));
        }
        return built;
    }();
    return patches;
}

// Splice `patch` (of `patchLen` bytes) at position `pos` inside [Data, Data+Size],
// without exceeding MaxSize.  Returns new size.
inline size_t splice(uint8_t *Data, size_t Size, size_t MaxSize,
                     size_t pos, const uint8_t *patch, size_t patchLen)
{
    if (pos > Size || patchLen == 0) return Size;
    const size_t tail   = Size - pos;
    const size_t newEnd = std::min(pos + patchLen + tail, MaxSize);
    // Shift tail right to make room (may truncate if MaxSize is tight)
    const size_t keep = std::min(tail, newEnd - std::min(pos + patchLen, newEnd));
    if (pos + patchLen < newEnd)
        std::memmove(Data + pos + patchLen, Data + pos, keep);
    const size_t copy = std::min(patchLen, newEnd - pos);
    std::memcpy(Data + pos, patch, copy);
    return newEnd;
}

// One structure-aware operation on raw bytes (an undecoded input, or a decoded body); op 0 and 4 write an old
// version's header at byte 0, which only an undecoded input takes
inline size_t mutateRaw(uint8_t *Data, size_t Size, size_t MaxSize, std::mt19937 &rng, int op)
{
    if (Size == 0 || MaxSize == 0)
        return LLVMFuzzerMutate(Data, Size, MaxSize);

    const auto randomPos = [&] { return Size > 1 ? std::uniform_int_distribution<size_t>(0, Size - 1)(rng) : 0; };

    switch (op) {
    case 0: { // patch_version: write a known version field at byte 4
        const auto &vp = kVersions[rng() % std::size(kVersions)];
        const size_t patchOff = 4; // right after "WPCF"
        if (Size >= patchOff + sizeof(vp.bytes) && MaxSize >= patchOff + sizeof(vp.bytes)) {
            std::memcpy(Data + patchOff, vp.bytes, sizeof(vp.bytes));
            return Size;
        }
        break;
    }
    case 1: { // patch_map_key: splice a known key at a random byte offset
        const auto &key = kMapKeys[rng() % std::size(kMapKeys)];
        // Find how long this key is (4 byte-len header + key bytes)
        const uint32_t keyDataLen = (uint32_t(key[0])<<24)|(uint32_t(key[1])<<16)
                                   |(uint32_t(key[2])<<8)|key[3];
        const size_t totalLen = 4 + keyDataLen;
        return splice(Data, Size, MaxSize, randomPos(), key, totalLen);
    }
    case 2: { // patch_type_id: splice a known QMetaType typeId at a random position
        const auto *tid = kTypeIds[rng() % std::size(kTypeIds)];
        return splice(Data, Size, MaxSize, randomPos(), tid, 4);
    }
    case 3: { // patch_element_type: splice a valid ElementType as quint64 big-endian
        const auto &types = elementPatches().types;
        const auto &ep = types[rng() % types.size()];
        return splice(Data, Size, MaxSize, randomPos(), ep.data(), ep.size());
    }
    case 4: { // patch_header: write WPCF magic + version at byte 0 (whole preamble)
        const auto &vp = kVersions[rng() % std::size(kVersions)];
        // Full preamble: 4-byte magic + 12-byte version = 16 bytes
        constexpr uint8_t magic[4] = {0x57, 0x50, 0x43, 0x46}; // "WPCF"
        if (MaxSize >= 16) {
            const size_t newSize = std::max(Size, size_t(16));
            if (newSize > Size && newSize <= MaxSize) {
                std::memset(Data + Size, 0, newSize - Size);
            }
            std::memcpy(Data, magic, 4);
            std::memcpy(Data + 4, vp.bytes, 12);
            return std::max(newSize, Size);
        }
        break;
    }
    case 5: { // patch_item_type: splice a GraphicElement or Connection type discriminator
        // These 4-byte big-endian values are the switch keys in Serialization::deserialize().
        const auto *it = kItemTypes[rng() % std::size(kItemTypes)];
        return splice(Data, Size, MaxSize, randomPos(), it, 4);
    }
    case 6: { // patch_element_seq: splice 12-byte GraphicElement::Type + ElementType quint64
        const auto &sequences = elementPatches().sequences;
        const auto &seq = sequences[rng() % sequences.size()];
        return splice(Data, Size, MaxSize, randomPos(), seq.data(), seq.size());
    }
    case 7: { // patch_appearance_entry: splice a valid appearances list entry with a skinName key
        return splice(Data, Size, MaxSize, randomPos(), kAppearanceEntry, sizeof(kAppearanceEntry));
    }
    default:
        break;
    }

    // fallback: let libFuzzer do its own mutation
    return LLVMFuzzerMutate(Data, Size, MaxSize);
}

// A WPCF input as the reader sees it: its version, and its body (everything after the header), decompressed when the
// version compresses it
struct DecodedInput {
    QVersionNumber version;
    QByteArray body;
};

inline std::optional<DecodedInput> decode(const uint8_t *data, size_t size)
{
    const QByteArray bytes = QByteArray::fromRawData(reinterpret_cast<const char *>(data), static_cast<qsizetype>(size));
    if (!bytes.startsWith("WPCF")) {
        return std::nullopt;
    }
    QDataStream stream(bytes);
    try {
        const QVersionNumber version = Serialization::readPandaHeader(stream);
        return DecodedInput{version, Serialization::readPayload(stream, version)};
    } catch (...) {
        return std::nullopt;
    }
}

inline QByteArray encode(const DecodedInput &input)
{
    QByteArray bytes;
    QDataStream stream(&bytes, QIODevice::WriteOnly);
    stream.setVersion(QDataStream::Qt_5_12);
    stream.writeRawData("WPCF", 4);
    stream << input.version.segments();
    if (VersionInfo::hasCompressedPayload(input.version)) {
        Serialization::writePayload(stream, input.body);
    } else {
        stream.writeRawData(input.body.constData(), static_cast<int>(input.body.size()));
    }
    return bytes;
}

/// Mutates the .panda file in [Data, Data + Size], within MaxSize, as LLVMFuzzerCustomMutator does: a WPCF input in
/// its decoded body (or switched to another version) and written back, anything else as raw bytes.
inline size_t mutate(uint8_t *Data, size_t Size, size_t MaxSize, unsigned int Seed)
{
    if (Size == 0 || MaxSize == 0)
        return LLVMFuzzerMutate(Data, Size, MaxSize);

    std::mt19937 rng(Seed);
    const int op = std::uniform_int_distribution<int>(0, 8)(rng);

    auto decoded = decode(Data, Size);
    if (!decoded) {
        return mutateRaw(Data, Size, MaxSize, rng, op);
    }
    // The fallback operation mutates even a decoded input's raw bytes, so the header and the compressed stream still
    // reach the reader corrupt: its decompression and size guards stay fuzzed
    if (op == 8) {
        return LLVMFuzzerMutate(Data, Size, MaxSize);
    }

    if ((op == 0) || (op == 4)) {
        decoded->version = kDecodedVersions[rng() % std::size(kDecodedVersions)];
    } else {
        // Room for the longest splice, or for libFuzzer's own mutation to grow the body
        QByteArray &body = decoded->body;
        const size_t bodySize = static_cast<size_t>(body.size());
        const size_t bodyMax = bodySize + 256;
        body.resize(static_cast<qsizetype>(bodyMax));
        const size_t newSize = mutateRaw(reinterpret_cast<uint8_t *>(body.data()), bodySize, bodyMax, rng, op);
        body.resize(static_cast<qsizetype>(newSize));
    }

    const QByteArray encoded = encode(*decoded);
    if (static_cast<size_t>(encoded.size()) > MaxSize) {
        return LLVMFuzzerMutate(Data, Size, MaxSize);
    }
    std::memcpy(Data, encoded.constData(), static_cast<size_t>(encoded.size()));
    return static_cast<size_t>(encoded.size());
}

